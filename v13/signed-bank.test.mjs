import assert from 'node:assert/strict';
import {inspectBankDescriptor,verifyDetachedP256,verifyBankBytes} from './signed-bank.mjs';
let count=0;const check=f=>{f();count++};
const bank={version:165,questions:[{id:'q1',q:'Question ?',a:['A','B','C','D'],ok:2}]};
const bytes=new TextEncoder().encode(JSON.stringify(bank));
const digest=Buffer.from(await crypto.subtle.digest('SHA-256',bytes)).toString('hex');
const d={version:165,minimum_app_version_code:13,question_count:1,byte_length:bytes.length,sha256:digest,file:'https://raw.githubusercontent.com/ifsi-quizz-2026/ifsi-quiz-updates/main/library-v165.json'};
check(()=>assert.equal(inspectBankDescriptor(d).version,165));
check(()=>assert.throws(()=>inspectBankDescriptor({...d,version:164}),/No newer/));
check(()=>assert.throws(()=>inspectBankDescriptor({...d,file:'https://evil.example/file.json'}),/Untrusted/));
check(()=>assert.throws(()=>inspectBankDescriptor({...d,byte_length:20_000_001}),/size/));
check(()=>assert.throws(()=>inspectBankDescriptor({...d,minimum_app_version_code:14}),/App update/));
check(()=>assert.throws(()=>inspectBankDescriptor({...d,sha256:'bad'}),/digest/));
assert.deepEqual(await verifyBankBytes(bytes,d),{version:165,questionCount:1});count++;
await assert.rejects(verifyBankBytes(bytes,{...d,sha256:'0'.repeat(64)}),/Digest mismatch/);count++;
const pair=await crypto.subtle.generateKey({name:'ECDSA',namedCurve:'P-256'},true,['sign','verify']);
const jwk=await crypto.subtle.exportKey('jwk',pair.publicKey);jwk.alg='ES256';
const sig=Buffer.from(await crypto.subtle.sign({name:'ECDSA',hash:'SHA-256'},pair.privateKey,bytes)).toString('base64');
assert.equal(await verifyDetachedP256(bytes,sig,jwk),true);count++;
assert.equal(await verifyDetachedP256(new TextEncoder().encode('tampered'),sig,jwk),false);count++;
console.log(count+' tests sécurité V13 réussis');
